package main

// Markdown 文档生成（供 /api/dev/docs）。
//
// 用缩进式代码块（不用反引号），避免转义麻烦。

import (
	"fmt"
	"strings"
)

// markdownDocs 生成完整的接入文档。
func (s *Server) markdownDocs() string {
	var b strings.Builder

	w := func(format string, a ...any) {
		fmt.Fprintf(&b, format+"\n", a...)
	}

	w("# MiCam API 接入文档")
	w("")
	w("版本: %s", appVersion)
	w("")
	w("---")
	w("")
	w("## 一、快速开始")
	w("")
	w("### 1.1 两种接入方式")
	w("")
	w("方式 A：局域网直连（推荐给桌面客户端）")
	w("")
	w("    http://<nas-ip>:8900")
	w("")
	w("方式 B：飞牛网关（插件内页面用）")
	w("")
	w("    http://<nas-ip>/app/micam")
	w("")
	w("### 1.2 第一步：探测能力")
	w("")
	w("    GET /api/health")
	w("    -> {\"app\":\"micam\",\"ok\":true,\"version\":\"x.y.z\"}")
	w("")
	w("    GET /api/dev/capabilities")
	w("    -> 硬件、支持的功能、限制（fps/分辨率）")
	w("")
	w("客户端应据此决定：")
	w("- 用 HLS 还是 MJPEG")
	w("- 最高分辨率取多少")
	w("- 哪些功能可显示")
	w("")
	w("### 1.3 第二步：拿到设备")
	w("")
	w("    GET /api/devices")
	w("    -> {\"devices\":[{\"did\":\"...\",\"name\":\"...\",\"isOnline\":true,\"shared\":false}]}")
	w("")
	w("共享设备字段 shared=true（来自别人分享的家庭）。")
	w("")
	w("### 1.4 第三步：播放")
	w("")
	w("首选 HLS：")
	w("")
	w("    <video src=\"http://<nas>:8900/api/live/hls?did=XXX&fps=15&w=0\">")
	w("")
	w("Safari 原生支持；其他浏览器用 hls.js。")
	w("重要：m3u8 里的分片行是相对路径，交给播放器解析即可，不要手工拼接。")
	w("")
	w("兜底 MJPEG：")
	w("")
	w("    <img src=\"http://<nas>:8900/api/live/mjpeg?did=XXX&fps=12&w=1280\">")
	w("")
	w("---")
	w("")
	w("## 二、摄像头 vs 其他设备")
	w("")
	w("本插件只做摄像头和存储监控。判断方法：")
	w("")
	w("    model 含 .camera. / .cateye. / .feeder.  -> 摄像头")
	w("")
	w("摄像头的控制走 cs2 P2P 私有协议（不是小米云 MIoT）：")
	w("")
	w("    0x100  auth      认证")
	w("    0x102  video     视频流")
	w("    0x106  speaker   对讲（命令已知，未实现）")
	w("    0x112  motor     云台（已实现）")
	w("    0x1001 encoded   编码包装")
	w("")
	w("---")
	w("")
	w("## 三、播放接口详解")
	w("")
	w("### 3.1 HLS（推荐）")
	w("")
	w("    GET /api/live/hls?did=XXX&fps=15&w=0")
	w("")
	w("参数：")
	w("")
	w("    did   设备 DID（必填）")
	w("    fps   帧率，默认 15，上限 15")
	w("    w     宽度，0=原画（2K 2560），可填 1280 / 640")
	w("    seg   分片文件名（内部使用，客户端不用传）")
	w("")
	w("返回 m3u8：")
	w("")
	w("    #EXTM3U")
	w("    #EXT-X-VERSION:3")
	w("    #EXT-X-TARGETDURATION:2")
	w("    #EXT-X-PLAYLIST-TYPE:EVENT")
	w("    #EXTINF:2.000000,")
	w("    hls?did=XXX&seg=seg0.ts")
	w("")
	w("**注意最后一行**：是相对路径且保留了 hls 段。")
	w("播放器按标准相对路径解析会得到正确地址。")
	w("如果手工拼接，必须拼成 /api/live/hls?did=XXX&seg=seg0.ts。")
	w("")
	w("性能（Intel J4125 实测）：")
	w("")
	w("    方案          CPU     首帧     2K")
	w("    MJPEG        335%    9-19s    卡")
	w("    HLS           94%     8s      流畅")
	w("")
	w("### 3.2 MJPEG（兼容）")
	w("")
	w("    GET /api/live/mjpeg?did=XXX&fps=12&w=1280")
	w("")
	w("Content-Type: multipart/x-mixed-replace; boundary=mjpegframe")
	w("")
	w("每帧格式：")
	w("")
	w("    --mjpegframe\r\n")
	w("    Content-Type: image/jpeg\r\n")
	w("    Content-Length: N\r\n")
	w("    \r\n")
	w("    <N 字节 JPEG>\r\n")
	w("")
	w("**重要**：macOS/iOS 的 CFNetwork 读不了 multipart/x-mixed-replace")
	w("（连 didReceiveResponse 都不回调）。需用裸 socket 读取。")
	w("可以按 Content-Length 切帧，也可以按 FFD8FF / FFD9 标记切。")
	w("")
	w("### 3.3 抓拍")
	w("")
	w("    GET /api/live/snapshot?did=XXX&w=0")
	w("    -> image/jpeg")
	w("")
	w("---")
	w("")
	w("## 四、云台")
	w("")
	w("    GET  /api/ptz/status?did=XXX")
	w("    POST /api/ptz/move   {\"did\":\"XXX\",\"operation\":N}")
	w("")
	w("operation：")
	w("")
	w("    1 = 查询位置")
	w("    2 = 左")
	w("    3 = 右")
	w("    4 = 下")
	w("    5 = 上")
	w("")
	w("响应：")
	w("")
	w("    {\"ok\":true,\"ret\":0,\"angle\":50,\"elevation\":73}")
	w("")
	w("**注意**：同一设备同时只能有一路 cs2 连接。")
	w("云台操作会短暂占用视频通道，客户端应串行化云台请求。")
	w("")
	w("---")
	w("")
	w("## 五、录像与存储")
	w("")
	w("    GET  /api/storage                       存储总览")
	w("    GET  /api/storage/cleanup-preview       清理预览")
	w("    GET  /api/recordings                    录像任务")
	w("    POST /api/recordings                    开始录像")
	w("    POST /api/recordings/stop               停止录像")
	w("    GET  /api/recordings/files?name=XXX     文件列表")
	w("    POST /api/recordings/cleanup            清理过期")
	w("")
	w("存储总览返回：")
	w("")
	w("    disk         磁盘容量（totalGB/usedGB/freeGB/usedPercent）")
	w("    recordings   录像占用（totalGB/fileCount/keepDays/minFreeGB）")
	w("    cameras      各摄像头明细（files/sizeMB/lastTime）")
	w("    estimateHours 按码率估算可录时长")
	w("")
	w("---")
	w("")
	w("## 六、错误处理")
	w("")
	w("### 6.1 HTTP 状态码")
	w("")
	w("    200  成功")
	w("    400  参数错误")
	w("    404  设备不存在")
	w("    405  方法不允许")
	w("    500  内部错误")
	w("    502  上游失败（摄像头/小米云）")
	w("    504  超时（HLS 播放列表未就绪，可重试）")
	w("")
	w("### 6.2 业务错误")
	w("")
	w("错误响应格式：")
	w("")
	w("    {\"msg\":\"错误描述\"}")
	w("")
	w("常见情况：")
	w("")
	w("    设备离线（<name>），无法播放      设备不在线")
	w("    miss: auth: {\"result\":\"failed\",\"code\":3}   凭据失效，稍后重试")
	w("    throttle deny                    小米云限流，等 30 分钟")
	w("    播放列表尚未生成，请稍候重试     HLS 转码启动中，重试即可")
	w("")
	w("### 6.3 重试建议")
	w("")
	w("    504          -> 2 秒后重试，最多 3 次")
	w("    auth failed  -> 3-5 秒后重试（服务端会自动刷新凭据）")
	w("    设备离线     -> 不要重试，提示用户")
	w("")
	w("---")
	w("")
	w("## 七、凭据与限流")
	w("")
	w("### 7.1 cs2 凭据有有效期")
	w("")
	w("实测 8 小时后可能失效。服务端会自动刷新，但小米云有限流：")
	w("")
	w("    throttle deny（code=-12）")
	w("")
	w("刷新失败时会保留旧凭据，并有 30 分钟冷却。")
	w("客户端只需重试，不要频繁请求。")
	w("")
	w("### 7.2 查询凭据状态")
	w("")
	w("    GET /api/live/source-status")
	w("    -> {\"devices\":[{\"did\":\"...\",\"hasSource\":true,\"ageMinutes\":120,\"cooldownMinutes\":0}]}")
	w("")
	w("---")
	w("")
	w("## 八、开放模式（开发者选项）")
	w("")
	w("连续点击侧边栏底部版本号 7 次解锁。")
	w("")
	w("    GET  /api/dev/status        解锁状态与开关")
	w("    POST /api/dev/tap           点击计数（解锁用）")
	w("    POST /api/dev/config        修改开关")
	w("    GET  /api/dev/capabilities  能力探测")
	w("    GET  /api/dev/openapi       OpenAPI 3.0 规格")
	w("    GET  /api/dev/docs          本文档")
	w("")
	w("开关说明：")
	w("")
	w("    cors        允许跨域（网页端 / Electron 调试用）")
	w("    allowLan    允许局域网直连（默认开）")
	w("    verboseLog  详细日志")
	w("    mockMode    模拟数据（不连真设备，UI 开发用）")
	w("    exposeSpec  暴露规格文档接口")
	w("")
	w("---")
	w("")
	w("## 九、接口自测")
	w("")
	w("命令行：")
	w("")
	w("    # 健康检查")
	w("    curl http://<nas>:8900/api/health")
	w("")
	w("    # 设备列表")
	w("    curl http://<nas>:8900/api/devices")
	w("")
	w("    # HLS 播放列表")
	w("    curl http://<nas>:8900/api/live/hls?did=XXX")
	w("")
	w("    # 抓拍存文件")
	w("    curl -o snap.jpg http://<nas>:8900/api/live/snapshot?did=XXX")
	w("")
	w("    # OpenAPI 规格（可导入 Postman / Insomnia）")
	w("    curl -o micam.json http://<nas>:8900/api/dev/openapi")
	w("")
	w("---")
	w("")
	w("## 十、版本兼容")
	w("")
	w("    0.7.x   当前。HLS + MJPEG + 云台 + 录像 + 存储监控")
	w("    0.6.x   加入 HLS")
	w("    0.5.x   诊断导出")
	w("    0.3.x   早期 MJPEG 版本")
	w("")
	w("接口变更遵循：")
	w("    新增接口       -> patch 版本")
	w("    修改响应字段   -> minor 版本，保留旧字段")
	w("    删除接口       -> major 版本")
	w("")

	return b.String()
}
